#!/usr/bin/env python3
"""Import the story CGs shown by the Hub's 剧情背景 theme.

The owner's source folder is a collection of story illustrations (PNG, ~720p–1080p). The Hub offers ONE
`剧情背景` tile — not a gallery — and picks one of these images per visit; 「换一张」 cycles to another.
The files are ordinary static assets under public/assets/ui/hub/story/ and are NOT in data/assets.json:
the boot art preloader must never pull all of them (each is only fetched when it is the chosen background).

Usage:
  py -3.14 tools/assets/hub-story.py --src "C:/Users/…/新建文件夹"
  py -3.14 tools/assets/hub-story.py --src "…" --max-edge 1920 --quality 85 --force
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'public' / 'assets' / 'ui' / 'hub' / 'story'
JS = ROOT / 'public' / 'js' / 'ui' / 'hub' / 'storyImages.js'


def main() -> int:
    ap = argparse.ArgumentParser(description='Convert the story CG folder into Hub story-background WebP assets.')
    ap.add_argument('--src', required=True, help='folder of story PNGs')
    ap.add_argument('--out', default=str(OUT), help=f'output folder (default {OUT})')
    ap.add_argument('--js', default=str(JS), help=f'generated image list (default {JS})')
    ap.add_argument('--max-edge', type=int, default=1920)
    ap.add_argument('--quality', type=int, default=85)
    ap.add_argument('--force', action='store_true', help='re-encode files that already exist')
    args = ap.parse_args()
    src = Path(args.src)
    if not src.is_dir():
        raise SystemExit(f'no source folder: {src}')
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    files = sorted((p for p in src.iterdir() if p.suffix.lower() in ('.png', '.jpg', '.jpeg', '.webp')), key=lambda p: p.name)
    rows = []
    total = 0
    skipped = 0
    for i, path in enumerate(files, 1):
        name = f'story-{i:02d}.webp'
        dst = out / name
        if not args.force and dst.exists() and dst.stat().st_size > 5000:
            skipped += 1
        else:
            with Image.open(path) as im:
                im = im.convert('RGBA')
                # flatten any alpha onto the Hub's ground colour (the CGs are opaque in practice)
                bg = Image.new('RGBA', im.size, (11, 17, 16, 255))
                bg.alpha_composite(im)
                im = bg.convert('RGB')
                im.thumbnail((args.max_edge, args.max_edge), Image.LANCZOS)
                im.save(dst, 'WEBP', quality=args.quality, method=6)
            print(f'[{i}/{len(files)}] {path.name} -> {name} ({dst.stat().st_size // 1024} KB)', flush=True)
        total += dst.stat().st_size
        rows.append({'file': f'/assets/ui/hub/story/{name}', 'name': path.stem})
    js = ['// i18n-ignore-file — story image titles are metadata, not interface text.',
          '// Generated by tools/assets/hub-story.py — the Hub 剧情背景 images (one tile, not a gallery).',
          'export const STORY_IMAGES = Object.freeze([']
    js += [f"  {{ file: {json.dumps(r['file'])}, name: {json.dumps(r['name'], ensure_ascii=False)} }}," for r in rows]
    js += [']);', '']
    Path(args.js).write_text('\n'.join(js), encoding='utf-8')
    print(f'{len(rows)} images, {total / 1048576:.1f} MB, {skipped} existing -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
